/** Word forms for 1, for 2–4 (but not 12–14) and for the rest; English uses the first and the last. */
type Forms = [string, string, string];

const enPlurals = {
  dictations: ["dictation", "dictations", "dictations"] as Forms,
  credits: ["credit", "credits", "credits"] as Forms,
  days: ["day", "days", "days"] as Forms,
  requests: ["request", "requests", "requests"] as Forms,
};

export type PluralKey = keyof typeof enPlurals;

const plPlurals: Record<PluralKey, Forms> = {
  dictations: ["dyktowanie", "dyktowania", "dyktowań"],
  credits: ["kredyt", "kredyty", "kredytów"],
  days: ["dzień", "dni", "dni"],
  requests: ["zapytanie", "zapytania", "zapytań"],
};

let current: Lang = "en";

export const lang = (): Lang => current;
/** Locale for `Intl` number and date formats. */
export const locale = (): string => (current === "pl" ? "pl-PL" : "en-US");

export function setLang(l: Lang): void {
  current = l === "pl" ? "pl" : "en";
  document.documentElement.lang = current;
}

/** The text of `key`, with `{name}` placeholders filled from `vars`. */
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const text = (current === "pl" ? pl : en)[key];
  return text.replace(/\{(\w+)\}/g, (all, name: string) => (name in vars ? String(vars[name]) : all));
}

/** The form of `key` that goes with `n`. */
export function plural(n: number, key: PluralKey): string {
  const [one, few, many] = (current === "pl" ? plPlurals : enPlurals)[key];
  const k = Math.abs(Math.round(n));
  if (k === 1) return one;
  if (current === "en") return many;
  return k % 10 >= 2 && k % 10 <= 4 && (k % 100 < 12 || k % 100 > 14) ? few : many;
}

const ATTRS = ["placeholder", "title", "aria-label"] as const;

/**
 * Fill the page's static texts: `data-t` sets the text, `data-t-html` the
 * markup (only for trusted texts from this file), `data-t-<attr>` an attribute.
 */
export function translatePage(): void {
  const get = (key: string | undefined): string => {
    if (key && key in en) return t(key as Key);
    console.error(`i18n: no text "${key}"`);
    return key ?? "";
  };
  document.querySelectorAll<HTMLElement>("[data-t]").forEach((e) => (e.textContent = get(e.dataset.t)));
  document.querySelectorAll<HTMLElement>("[data-t-html]").forEach((e) => (e.innerHTML = get(e.dataset.tHtml)));
  for (const attr of ATTRS) {
    document.querySelectorAll<HTMLElement>(`[data-t-${attr}]`).forEach((e) => e.setAttribute(attr, get(e.getAttribute(`data-t-${attr}`) ?? undefined)));
  }
}
